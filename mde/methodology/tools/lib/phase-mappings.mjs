/**
 * Assign each metamodel concept to a phase index.
 * @param {string} level
 * @param {string[]} concepts
 * @returns {Map<string, number>}
 */
export function assignConceptsToPhases(level, concepts) {
  const specs = PHASE_SPECS[level];
  const assignment = new Map();
  const explicit = new Map();
  specs.forEach((spec, index) => {
    for (const type of spec.types) {
      explicit.set(type, index);
    }
  });

  for (const concept of concepts) {
    if (explicit.has(concept)) {
      assignment.set(concept, explicit.get(concept));
      continue;
    }
    if (KERNEL_TYPES.has(concept)) {
      assignment.set(concept, specs.findIndex((s) => s.kernelPhase));
      continue;
    }
    if (SHARED_READINESS_TYPES.has(concept)) {
      assignment.set(
        concept,
        specs.findIndex((s) => s.readinessPhase),
      );
      continue;
    }
    if (SHARED_ENUMS.has(concept)) {
      assignment.set(concept, 0);
      continue;
    }
    // Heuristic fallback: assign to readiness phase to avoid orphans
    const readinessIdx = specs.findIndex((s) => s.readinessPhase);
    assignment.set(concept, readinessIdx >= 0 ? readinessIdx : specs.length - 1);
  }
  return assignment;
}
